/**
 * Typed schema for the content files in `public/` (`points.json`, `transcription.json`).
 *
 * All coordinates are normalized to the image: `0` is the left/top edge and `1` the
 * right/bottom edge, so the data survives replacing the placeholder photo with the scan.
 */
import { z } from 'zod';

const unit = z.number().min(0).max(1);

/** A position on the image, normalized 0–1. */
export const pointSchema = z.object({ x: unit, y: unit }).strict();

/** A rectangle on the image, normalized 0–1, that must lie fully inside the image. */
export const regionSchema = z
  .object({ x: unit, y: unit, width: unit.positive(), height: unit.positive() })
  .strict()
  .refine((r) => r.x + r.width <= 1 + 1e-9 && r.y + r.height <= 1 + 1e-9, {
    message: 'region must lie inside the image',
  });

/**
 * Text in every supported language. Serbian is written in Cyrillic; the Latin version is
 * generated by transliteration. English is optional until translations exist.
 */
export const localizedTextSchema = z
  .object({ sr: z.string().min(1), en: z.string().optional() })
  .strict();

const slug = z.string().regex(/^[a-z0-9-]+$/, 'ids must be lowercase ASCII (used in URLs)');

/** One explained area of the document (a pin). */
export const documentPointSchema = z
  .object({
    id: slug,
    title: localizedTextSchema,
    body: z.array(localizedTextSchema).min(1),
    region: regionSchema,
    /** Pin position; defaults to the center of `region`. */
    pin: pointSchema.optional(),
    /** Notes for the author about facts that still need checking (shown in dev mode). */
    verify: z.array(z.string()).optional(),
  })
  .strict();

export /**
 *
 */
const pointsFileSchema = z
  .object({ points: z.array(documentPointSchema).min(1) })
  .strict()
  .superRefine((file, ctx) => {
    const seen = new Set<string>();

    for (const [index, point] of file.points.entries()) {
      if (seen.has(point.id)) {
        ctx.addIssue({
          code: 'custom',
          message: `duplicate id "${point.id}"`,
          path: ['points', index, 'id'],
        });
      }

      seen.add(point.id);
    }
  });

/** One line of the transcription, as laid out on the document. */
export const transcriptionLineSchema = z
  .object({
    id: slug,
    /** Text as written on the document (Cyrillic). */
    text: z.string().min(1),
    /** Modern explanation of the line, if it needs one. */
    gloss: localizedTextSchema.optional(),
    region: regionSchema,
    /** The line is not transcribed yet; `text` describes what is there. */
    placeholder: z.boolean().optional(),
  })
  .strict();

export /**
 *
 */
const transcriptionSectionSchema = z
  .object({
    id: slug,
    title: localizedTextSchema,
    lines: z.array(transcriptionLineSchema).min(1),
  })
  .strict();

export /**
 *
 */
const transcriptionFileSchema = z
  .object({
    intro: localizedTextSchema,
    sections: z.array(transcriptionSectionSchema).min(1),
    verify: z.array(z.string()).optional(),
  })
  .strict();

/** Normalized point on the image. */
export type ImagePoint = z.infer<typeof pointSchema>;
/** Normalized rectangle on the image. */
export type Region = z.infer<typeof regionSchema>;
/** Text in all supported languages. */
export type LocalizedText = z.infer<typeof localizedTextSchema>;
/** One explained area of the document. */
export type DocumentPoint = z.infer<typeof documentPointSchema>;
/** Contents of `points.json`. */
export type PointsFile = z.infer<typeof pointsFileSchema>;
/** One transcription line. */
export type TranscriptionLine = z.infer<typeof transcriptionLineSchema>;
/** A group of transcription lines (heading, decree, ...). */
export type TranscriptionSection = z.infer<typeof transcriptionSectionSchema>;
/** Contents of `transcription.json`. */
export type TranscriptionFile = z.infer<typeof transcriptionFileSchema>;

/** Result of validating untrusted data. */
export type ParseResult<T> = { ok: true; value: T } | { ok: false; errors: string[] };

/**
 * Validate untrusted JSON against a schema, returning readable error messages.
 *
 * @param schema - The zod schema to validate against.
 * @param data - Parsed JSON of unknown shape.
 * @returns The typed value, or a list of `path: message` errors.
 */
export function parseWith<T>(schema: z.ZodType<T>, data: unknown): ParseResult<T> {
  const result = schema.safeParse(data);

  if (result.success) {
    return { ok: true, value: result.data };
  }

  return {
    ok: false,
    errors: result.error.issues.map(
      (issue) => `${issue.path.join('.') || '(root)'}: ${issue.message}`,
    ),
  };
}

/**
 * Pin position of a point: the explicit `pin`, or the center of its region.
 *
 * @param point - The document point.
 * @returns Normalized pin position.
 */
export function pinPosition(point: DocumentPoint): ImagePoint {
  return (
    point.pin ?? {
      x: point.region.x + point.region.width / 2,
      y: point.region.y + point.region.height / 2,
    }
  );
}
